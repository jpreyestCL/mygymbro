#!/usr/bin/env node
// Generate ios/Podfile from Capacitor's ios/App/Podfile, for EAS Build only.
//
// EAS runs `pod install` with the iOS directory as its working directory, because that is where
// a React Native project keeps its Podfile. Capacitor keeps the whole Xcode project one level
// deeper, in ios/App, so EAS finds nothing and the build dies with:
//
//     [!] No `Podfile' found in the project directory.
//
// A symlink does not fix it: the real Podfile reaches its dependencies through `../../node_modules`,
// which is correct from ios/App and points outside the project from ios/. So this writes a real
// Podfile at ios/ with the paths shifted up one level and the project named explicitly. CocoaPods
// then integrates with the same ios/App/App.xcodeproj and emits ios/App.xcworkspace — exactly where
// EAS looks for it next.
//
// It is GENERATED, never hand-edited: adding a Capacitor plugin rewrites ios/App/Podfile, and a
// hand-maintained copy would rot silently into a build that is missing a plugin. `npm run
// build:mobile` regenerates it, so the two cannot drift.
//
// Nothing local reads it. `cap sync` runs pod install inside ios/App, and Xcode opens
// ios/App/App.xcworkspace, both as before.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = path.join(root, 'ios', 'App', 'Podfile')
const target = path.join(root, 'ios', 'Podfile')

if (!fs.existsSync(source)) {
  console.error(`gen-eas-podfile: no Podfile at ${source} — has \`cap add ios\` run?`)
  process.exit(1)
}

const original = fs.readFileSync(source, 'utf8')

// One level shallower: ios/App/Podfile → ios/Podfile.
let out = original.replaceAll('../../node_modules', '../node_modules')

if (out.includes('../../')) {
  console.error('gen-eas-podfile: the Podfile still has un-rewritten ../../ paths:')
  console.error(out.split('\n').filter(l => l.includes('../../')).map(l => '  ' + l.trim()).join('\n'))
  process.exit(1)
}

// Name the project explicitly. Without this CocoaPods looks for an .xcodeproj beside the Podfile
// and would pick up the ios/App.xcodeproj symlink, integrating through it rather than through the
// real path.
const PROJECT = "project 'App/App.xcodeproj'"
out = out.replace(/^(install! .*)$/m, `$1\n\n${PROJECT}`)
out = out.replace(/^(target 'App' do)$/m, `$1\n  ${PROJECT}`)

if (!out.includes(PROJECT)) {
  console.error('gen-eas-podfile: could not find where to declare the project — has the Podfile template changed?')
  process.exit(1)
}

const header = `# GENERATED by scripts/gen-eas-podfile.mjs — do not edit.
# Source of truth is ios/App/Podfile, which Capacitor owns. This copy exists only so EAS Build,
# which runs \`pod install\` from ios/, can find a Podfile at all. Run \`npm run build:mobile\`
# to regenerate. Do not run \`pod install\` from ios/ locally: it would re-integrate the Xcode
# project against ios/Pods, and \`cap sync\` expects ios/App/Pods.

`

fs.writeFileSync(target, header + out)
console.log(`gen-eas-podfile: wrote ${path.relative(root, target)} from ${path.relative(root, source)}`)
